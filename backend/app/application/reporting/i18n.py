def t(locale: str, key: str, **values) -> str:
    text = T.get(locale, T["en"]).get(key) or T["en"].get(key) or key
    if values:
        try:
            return text.format(**{k: v for k, v in values.items()})
        except (KeyError, IndexError, ValueError):
            return text
    return text


def num(value: Optional[float], locale: str, decimals: int = 1) -> str:
    if value is None:
        return t(locale, "chrome.missing")
    text = f"{value:,.{decimals}f}" if decimals else f"{int(round(value)):,}"
    if locale == "ar":
        text = text.replace(",", "٬").translate(_AR_DIGITS)
    return text


def pct(value: Optional[float], locale: str, decimals: int = 1) -> str:
    if value is None:
        return t(locale, "chrome.missing")
    return f"{num(value, locale, decimals)}٪" if locale == "ar" else f"{num(value, locale, decimals)}%"


def day(value, locale: str) -> str:
    if value is None:
        return t(locale, "chrome.missing")
    if isinstance(value, str):
        value = datetime.fromisoformat(value.replace("Z", "+00:00")) if "T" in value else date.fromisoformat(value)
    d = value.date() if isinstance(value, datetime) else value
    text = f"{d.day} {_MONTHS[locale if locale in _MONTHS else 'en'][d.month - 1]} {d.year}"
    return text.translate(_AR_DIGITS) if locale == "ar" else text


def humanize(label: Optional[str]) -> str:
    if not label:
        return ""
    text = label.replace("___", " ").replace("_", " ").strip()
    return text[:1].upper() + text[1:]


